function demo(): LXS {
  return new LXS({ service: 'shop' })
    .create('web-admin', '/admin', { brand: 'Acme Shop' })
    .create('web-bait', '/.env')
    .create('web-bait', '/backup.sql')
    .create('ssh', 22, { hostname: 'db-backup-01' })
    .asset('/api/payments/*', { name: 'Payments API', criticality: 'critical' })
    .honeytokens({ apiKey: { header: 'authorization', prefix: 'acme_live_' } });
}

test('compose output keeps the containment posture from BREAKDOWN 5.4', () => {
  const g = generateAll(demo().resolve());
  const text = g.committed.get('lxs.compose.yml') as string;
  assert.match(text, /^# lxs\.compose\.yml\n# Generated by lxs 0\.1\.0 .* do not edit by hand\./);
  const doc = parseYaml(text, { merge: true }) as any;

  assert.equal(doc.services['ds-web'].network_mode, 'none');
  assert.equal(doc.services['ds-web'].user, '10002:10002');
  assert.deepEqual(doc.services['ds-ssh-db-backup-01'].networks, ['ds_trap']);
  assert.deepEqual(doc.services['ds-agent'].networks, ['ds_uplink']);
  for (const svc of ['ds-web', 'ds-agent', 'ds-ssh-db-backup-01']) {
    const s = doc.services[svc];
    assert.equal(s.read_only, true, `${svc} read_only`);
    assert.deepEqual(s.cap_drop, ['ALL'], `${svc} cap_drop`);
    assert.deepEqual(s.security_opt, ['no-new-privileges:true'], `${svc} no-new-privileges`);
    assert.ok(s.mem_limit && s.pids_limit && s.cpus, `${svc} limits`);
  }
  // Only the agent holds the platform key; ds-web and cowrie never see env_file or the agent socket.
  assert.deepEqual(doc.services['ds-agent'].env_file, ['.env.lxs']);
  assert.equal(doc.services['ds-web'].env_file, undefined);
  assert.equal(doc.services['ds-ssh-db-backup-01'].env_file, undefined);
  const webVols = (doc.services['ds-web'].volumes as string[]).join('\n');
  assert.ok(!webVols.includes('ds_agent_sock'));
  assert.equal(
    doc.networks.ds_trap.driver_opts['com.docker.network.bridge.enable_ip_masquerade'],
    'false',
  );
  assert.equal(doc.networks.ds_trap.driver_opts['com.docker.network.bridge.enable_icc'], 'false');
  assert.deepEqual(doc.services.shop.environment, { LXS_RUN_DIR: '/run/lxs' });
  assert.deepEqual(doc.services['ds-ssh-db-backup-01'].ports, ['22:2222']);
});

test('Redis and Postgres render as isolated, bounded network decoys', () => {
  const cfg = new LXS({ service: 'shop' })
    .create('redis', 6380, { seed: 'finance', requirePassword: true })
    .create('postgres', 5433, { seed: 'shop', requirePassword: true })
    .resolve();
  const generated = generateAll(cfg);
  const doc = parseYaml(generated.committed.get('lxs.compose.yml') as string, {
    merge: true,
  }) as any;
  const redis = doc.services['ds-redis-6380'];
  const postgres = doc.services['ds-postgres-5433'];

  assert.equal(redis.read_only, true);
  assert.deepEqual(redis.cap_drop, ['ALL']);
  assert.deepEqual(redis.networks, ['ds_trap']);
  assert.deepEqual(redis.ports, ['6380:6379']);
  assert.equal(redis.environment.LXS_REDIS_REQUIRE_PASSWORD, '1');
  assert.equal(redis.env_file, undefined);

  assert.equal(postgres.read_only, true);
  assert.equal(postgres.user, '70:70');
  assert.deepEqual(postgres.cap_drop, ['ALL']);
  assert.deepEqual(postgres.networks, ['ds_trap']);
  assert.deepEqual(postgres.ports, ['5433:5432']);
  assert.equal(postgres.environment.POSTGRES_HOST_AUTH_METHOD, 'scram-sha-256');
  assert.equal(postgres.env_file, undefined);
  assert.ok(
    (postgres.tmpfs as string[]).some((v) => v.startsWith('/var/lib/postgresql/data:size=128m')),
  );
  assert.match(postgres.command.join(' '), /max_connections=16/);
  assert.match(postgres.command.join(' '), /temp_file_limit=16MB/);
  assert.ok(
    (postgres.volumes as string[]).some((v) => v.includes('init.sql:') && v.endsWith(':ro')),
  );
  const initSql = generated.committed.get('.lxs/postgres-5433/init.sql') as string;
  assert.ok(initSql.includes('ALTER ROLE postgres NOLOGIN'));
  assert.ok(initSql.includes('GRANT SELECT ON ALL TABLES'));
  assert.ok(!initSql.includes('GRANT INSERT'));
  assert.equal(
    doc.networks.ds_trap.driver_opts['com.docker.network.bridge.enable_ip_masquerade'],
    'false',
  );
  assert.equal(doc.networks.ds_trap.driver_opts['com.docker.network.bridge.enable_icc'], 'false');
});

test('no secret or key ever lands in committed output; plaintext goes to the secrets dir', () => {
  const g = generateAll(demo().resolve());
  const token = g.honeytokens.tokens.find((t) => t.kind === 'api_key')?.value as string;
  assert.match(token, /^acme_live_[A-Za-z0-9]{32}$/);
  for (const [file, content] of g.committed) {
    assert.ok(!content.includes(token), `${file} leaks the honeytoken`);
    assert.ok(
      !content.includes(g.honeytokens.credentials.ssh.password),
      `${file} leaks the bait password`,
    );
    assert.ok(!content.includes('ds_live_'), `${file} mentions a key`);
  }
  const secrets = [...g.secrets.keys()];
  assert.ok(secrets.includes('.lxs/secrets/.gitignore'));
  assert.ok(secrets.includes('.lxs/secrets/honeytokens.json'));
  assert.ok(secrets.includes('.lxs/secrets/ssh-db-backup-01/userdb.txt'));
  assert.ok(secrets.some((s) => s.endsWith('honeyfs/home/deploy/.config/acme.json')));
  const cowrie = g.committed.get('.lxs/ssh-db-backup-01/cowrie.cfg') as string;
  assert.match(cowrie, /forwarding = false/);
  assert.match(cowrie, /\[output_jsonlog\]\nenabled = true/);
  assert.match(cowrie, /\[telnet\]\nenabled = false/);
});

test('generation is idempotent when existing honeytokens are reused', () => {
  const a = generateAll(demo().resolve());
  const b = generateAll(demo().resolve(), { existingHoneytokens: a.honeytokens });
  assert.deepEqual([...a.committed], [...b.committed]);
  assert.equal(
    b.secrets.get('.lxs/secrets/honeytokens.json'),
    a.secrets.get('.lxs/secrets/honeytokens.json'),
  );
});

function project(config: string): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-proj-'));
  fs.writeFileSync(path.join(dir, 'docker-compose.yml'), 'services:\n  shop:\n    image: shop\n');
  fs.writeFileSync(path.join(dir, '.gitignore'), '.env.lxs\n.lxs/secrets/\n');
  fs.writeFileSync(path.join(dir, 'decoy.config.mjs'), config);
  return dir;
}

const CONFIG = `export default {
  service: 'shop',
  decoys: [
    { type: 'web-admin', path: '/admin', brand: 'Acme Shop' },
    { type: 'web-bait', path: '/.env' },
    { type: 'ssh', port: 22, hostname: 'db-backup-01' },
  ],
  assets: [{ pattern: '/api/payments/*', name: 'Payments API', criticality: 'critical' }],
  honeytokens: { apiKey: { header: 'authorization', prefix: 'acme_live_' } },
};`;

test('build writes the compose file + .lxs, and --check detects drift', async () => {
  const dir = project(CONFIG);
  const logs: string[] = [];
  const log = (m: string) => logs.push(m);
  assert.equal(await runBuild({ cwd: dir, log }), 0);
  assert.ok(fs.existsSync(path.join(dir, 'lxs.compose.yml')));
  assert.ok(fs.existsSync(path.join(dir, '.lxs/manifest.json')));
  assert.ok(fs.existsSync(path.join(dir, '.lxs/secrets/.gitignore')));
  assert.match(
    logs.join('\n'),
    /3 decoys: web-admin \/admin · web-bait \/\.env · ssh :22 \(db-backup-01\)/,
  );

  assert.equal(await runBuild({ cwd: dir, check: true, log }), 0);
  fs.appendFileSync(path.join(dir, 'lxs.compose.yml'), '# tampered\n');
  assert.equal(await runBuild({ cwd: dir, check: true, log }), 1);
  assert.equal(await runBuild({ cwd: dir, log }), 0); // rebuild repairs it
  assert.equal(await runBuild({ cwd: dir, check: true, log }), 0);
});

test('build refuses when secrets are not git-ignored, the service is missing, or a key is in the config', async () => {
  const quiet = () => undefined;
  const a = project(CONFIG);
  fs.writeFileSync(path.join(a, '.gitignore'), 'node_modules\n');
  await assert.rejects(runBuild({ cwd: a, log: quiet }), /E_NOT_GITIGNORED/);

  const b = project(CONFIG.replace("service: 'shop'", "service: 'nope'"));
  await assert.rejects(runBuild({ cwd: b, log: quiet }), /E_SERVICE_MISSING/);

  const c = project(`${CONFIG}\n// ds_live_0123456789abcdef`);
  await assert.rejects(runBuild({ cwd: c, log: quiet }), /E_KEY_IN_CONFIG/);
});

test('init scaffolds the config, env files and gitignore entries without clobbering', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-init-'));
  fs.writeFileSync(path.join(dir, '.gitignore'), 'node_modules');
  runInit({ cwd: dir, service: 'shop', log: () => undefined });
  assert.match(fs.readFileSync(path.join(dir, 'decoy.config.ts'), 'utf8'), /service: 'shop'/);
  const gi = fs.readFileSync(path.join(dir, '.gitignore'), 'utf8');
  assert.match(gi, /\.env\.lxs\n/);
  assert.match(gi, /\.lxs\/secrets\//);
  assert.ok(fs.existsSync(path.join(dir, '.env.lxs.example')));
  fs.writeFileSync(path.join(dir, 'decoy.config.ts'), '// mine');
  runInit({ cwd: dir, service: 'shop', log: () => undefined });
  assert.equal(fs.readFileSync(path.join(dir, 'decoy.config.ts'), 'utf8'), '// mine');
});
