import { z } from 'zod';

/** Every normalised signal that reaches the platform is one of these types. */
export const EventType = z.enum([
  'connection.open',
  'connection.close',
  'http.request',
  'auth.attempt',
  'command.exec',
  'file.download',
  'file.upload',
  'proxy.attempt',
  'ssh.client',
  'db.command',
  'honeytoken.read',
  'honeytoken.use',
  'asset.access',
  'asset.blocked',
  'prod.firewall',
  'prod.auth',
]);
export type EventType = z.infer<typeof EventType>;

export const SensorKind = z.enum(['web', 'ssh', 'redis', 'postgres', 'sdk', 'prod']);
export type SensorKind = z.infer<typeof SensorKind>;

export const Outcome = z.enum(['success', 'failure', 'unknown']);
export type Outcome = z.infer<typeof Outcome>;

/**
 * THE contract. Flat on purpose: easy to index in Postgres, easy to map to ECS later.
 * Server-assigned fields (project_id, received_at, incident_id, ...) are not part of it.
 * schema_version is literal 1 — add fields, never remove them.
 */
export const DecoyEvent = z.object({
  id: z.string().min(20).max(40), // ULID, generated by the agent; the idempotency key
  schema_version: z.literal(1),
  timestamp: z.string().datetime(), // sensor clock, UTC
  sensor: SensorKind,
  decoy_id: z.string().max(64).optional(), // stable id from decoy.config.ts
  is_decoy: z.boolean(), // false for sdk/prod signals about real assets
  session_id: z.string().max(128).optional(),
  src_ip: z.union([z.ipv4(), z.ipv6()]),
  src_port: z.number().int().min(0).max(65535).optional(),
  dst_service: z.string().max(128), // "ssh:22", "http:/admin", "app:/api/payments"
  event_type: EventType,
  outcome: Outcome.optional(),
  username: z.string().max(256).optional(),
  password_clear: z.string().max(128).optional(), // only when in the bundled common-creds list
  password_masked: z.string().max(128).optional(), // "a***n"
  password_sha256: z.string().length(64).optional(), // sha256(project salt + password)
  command: z.string().max(4096).optional(),
  method: z.string().max(16).optional(),
  url: z.string().max(2048).optional(),
  status_code: z.number().int().optional(),
  user_agent: z.string().max(512).optional(),
  payload: z.string().max(4096).optional(), // body excerpt; never executed
  file_name: z.string().max(512).optional(),
  file_sha256: z.string().length(64).optional(),
  file_size: z.number().int().nonnegative().optional(),
  client_banner: z.string().max(256).optional(),
  asset_name: z.string().max(128).optional(),
  honeytoken_id: z.string().max(64).optional(),
  count: z.number().int().positive().default(1), // > 1 when the agent aggregated repeats
  simulated: z.boolean().default(false),
  raw: z.record(z.string(), z.unknown()).optional(), // original record, capped at 4 KB
});
export type DecoyEvent = z.infer<typeof DecoyEvent>;

export const IngestBatch = z.object({
  sensor_id: z.string().max(128).optional(),
  events: z.array(DecoyEvent).min(1).max(500),
});
export type IngestBatch = z.infer<typeof IngestBatch>;
